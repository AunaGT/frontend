const test = require('node:test'), assert = require('node:assert/strict')
const { loadReportModule } = require('./helpers/loadReportModule.cjs')
const model = () => loadReportModule('../config/settingsModel.ts')
test('section payload excludes every unrelated key and logo is never a name draft', () => {
  const m = model()
  assert.deepEqual(m.sectionPayload('pedidos', { order_validity_days: '17', company_nit: 'NO' }), { order_validity_days: '17' })
  assert.deepEqual(m.sectionPayload('empresa', { company_name: 'Nueva', company_logo_url: 'https://no.invalid' }), { company_name: 'Nueva' })
  const keys = Object.values(m.SECTION_KEYS).flat()
  assert.equal(new Set(keys).size, keys.length)
  assert.equal(m.SETTINGS_SECTIONS.length, 12)
})
test('positive whole-day rules reject truncated, coercible or unsafe input', () => {
  const m = model()
  for (const value of ['0', '-1', '1.5', '7days', '', true, [], Number.MAX_SAFE_INTEGER + 1])
    assert.ok(m.validateSection('pedidos', { order_validity_days: value }).order_validity_days, String(value))
  assert.deepEqual(m.validateSection('pedidos', { order_validity_days: '17' }), {})
  assert.deepEqual(m.sectionPayload('pedidos', { order_validity_days: '1e2' }), { order_validity_days: '100' })
})
test('unknown, empty and zero stored values survive projection; defaults fill only missing keys', () => {
  const m = model()
  assert.equal(m.sectionValues('regional', { currency_code: 'LEGADO' }).currency_code, 'LEGADO')
  assert.equal(m.sectionValues('pedidos', { order_validity_days: '' }).order_validity_days, '')
  assert.equal(m.sectionValues('caja', { cash_closure_max_diff_pct: '0' }).cash_closure_max_diff_pct, '0')
  assert.deepEqual(m.sectionValues('pedidos', {}), { order_validity_days: '7' })
  assert.ok(m.validateSection('regional', m.sectionValues('regional', { currency_code: 'LEGADO' })).currency_code)
  assert.ok(m.validateSection('regional', m.sectionValues('regional', { date_format: 'formato desconocido' })).date_format)
})
test('draft comparison ignores temporary denomination fields but catches real edits', () => {
  const m = model(), a = { cash_closure_denominations: [{ denomination: 100, type: 'Billete', quantity: 2 }] }
  assert.equal(m.sameSection('caja', a, { cash_closure_denominations: [{ denomination: 100, type: 'Billete' }] }), true)
  assert.equal(m.sameSection('caja', a, { cash_closure_denominations: [{ denomination: 50, type: 'Billete' }] }), false)
  assert.equal(m.sameSection('pedidos', { order_validity_days: '07' }, { order_validity_days: '7' }), true)
  assert.deepEqual(m.sectionPayload('caja', { cash_closure_denominations: [{ denomination: 0, type: 'Billete' }, { denomination: 25, type: 'Billete' }] }).cash_closure_denominations, [{ denomination: 25, type: 'Billete' }])
})
test('search finds settings by purpose and accent without any company values', () => {
  const m = model()
  assert.equal(m.findSettingsSections('billetes')[0].id, 'caja')
  assert.ok(m.findSettingsSections('vigéncia').some(s => s.id === 'cotizaciones'))
  assert.ok(m.findSettingsSections('servicios').some(s => s.id === 'inventario'))
  assert.equal(m.findSettingsSections(''), m.SETTINGS_SECTIONS)
  assert.deepEqual(m.findSettingsSections('ninguna-coincidencia'), [])
})
