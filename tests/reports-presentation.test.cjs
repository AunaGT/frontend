const test = require('node:test'), assert = require('node:assert/strict'), React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const { loadReportModule, renderReportsPage } = require('./helpers/loadReportModule.cjs')
const { fixture } = require('./fixtures/reportFixtures.cjs')
const { assertPaginationOutside } = require('./pagination-assertions.cjs')
test('data preview uses compact metrics above real tables, 10 rows and exterior pagination', () => {
  const { ReportDataPreview } = loadReportModule('components/ReportDataPreview.tsx'), html = renderToStaticMarkup(React.createElement(ReportDataPreview, { report: fixture() }))
  assert.ok(html.indexOf('metric-strip') < html.indexOf('<table'))
  assert.ok(html.includes('QA-0010')); assert.ok(!html.includes('QA-0011'))
  assert.ok(html.includes('Mostrando 1 a 10 de 26')); assertPaginationOutside(html)
})
test('catalog fails closed while modules load or error, and hides unavailable report routes', () => {
  assert.ok(renderReportsPage({ modules: null }).html.includes('Cargando reportes'))
  assert.ok(renderReportsPage({ moduleError: true }).html.includes('No se pudo cargar'))
  assert.ok(!renderReportsPage({ allowed: false }).html.includes('Preparar datos'))
  assert.ok(!renderReportsPage({ route: '/reportes?reporte=arbitrary' }).html.includes('Preparar datos'))
})
test('a preview without prepared data offers configuration, not a fictitious document', () => {
  const view = renderReportsPage()
  assert.ok(view.html.includes('Preparar datos')); assert.ok(!view.html.includes('Reportes y análisis'))
  assert.ok(view.nodes.some(n => n.props.onClick && n.props.children === 'Preparar datos'))
  assert.ok(view.html.includes('Restablecer'))
  assert.ok(view.html.includes('aria-label="Elegir reporte"'))
})
test('report panels use the established raised Auna surface rather than generic dark card tokens', () => {
  const fs = require('node:fs'), path = require('node:path')
  const css = fs.readFileSync(path.resolve(__dirname, '../src/modules/reports/reports.css'), 'utf8')
  assert.match(css, /\.report-catalog-entry,\.report-panel[^}]*background:\s*hsl\(var\(--auna-surface-card\)\)/)
  assert.match(css, /\.report-viewer-toolbar[^}]*background:\s*hsl\(var\(--auna-surface-header\)\)/)
})
test('viewer chunk load uses a recoverable local error state rather than an uncaught React.lazy rejection', () => {
  const fs = require('node:fs'), path = require('node:path'), source = fs.readFileSync(path.resolve(__dirname, '../src/modules/reports/pages/ReportsManagement.tsx'), 'utf8')
  assert.ok(!source.includes('lazy(() => import(\'../components/ReportDocumentPreview\')'))
  assert.match(source, /No se pudo cargar el visor/)
})
